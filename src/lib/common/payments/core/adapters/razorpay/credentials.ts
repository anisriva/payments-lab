import { z } from 'zod';
import { defineCredentials } from '../../contracts/credentials';

const input = z.object({
  keyId: z.string().regex(/^rzp_(test|live)_/, 'Starts with rzp_test_ or rzp_live_'),
  keySecret: z.string().min(1, 'Required'),
});

export const RAZORPAY_CREDENTIALS = defineCredentials({
  input,
  runtime: input.extend({ webhookSecret: z.string().min(16) }), // generated by Folio
  fields: {
    keyId: { label: 'Key ID', placeholder: 'rzp_test_…', help: 'Account & Settings → API Keys' },
    keySecret: { label: 'Key secret', secret: true, help: 'Shown only once when you generate the keys' },
  },
  displayHint: (c) => `${c.keyId.slice(0, 9)}••••${c.keyId.slice(-4)}`,
});

export type RazorpayCredentialsInput = z.infer<typeof input>;
export type RazorpayCredentials = z.infer<typeof RAZORPAY_CREDENTIALS.runtime>;
